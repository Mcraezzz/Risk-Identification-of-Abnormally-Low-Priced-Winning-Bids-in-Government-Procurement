# ===== 3. 公式序号标题修改 =====
# 查找单独一行的公式编号如 "（1）"、"（2）" 等，改为 "公式（1）"、"公式（2）"
formula_count = 0
for para in doc.paragraphs:
    text = para.text.strip()
    if re.match(r'^（\d+）$', text):
        num = re.match(r'^（(\d+)）$', text).group(1)
        para.text = f'公式（{num}）'
        formula_count += 1
    elif re.match(r'^\(\d+\)$', text):
        num = re.match(r'^\((\d+)\)$', text).group(1)
        para.text = f'公式（{num}）'
        formula_count += 1

