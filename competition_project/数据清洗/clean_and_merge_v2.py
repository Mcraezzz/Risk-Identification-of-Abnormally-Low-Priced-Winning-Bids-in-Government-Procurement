def mark_price_anomalies(row):
    """返回 (价格有效样本, 极端价格异常标记, 比例异常标记, 小金额标记)"""
    try:
        ratio = float(row['中标/预算比例'])
        budget = float(row['预算金额'])
        winning = float(row['中标金额'])
    except:
        return '否', '是', '是', '是'
    
    # 比例异常标记
    ratio_anomaly = '是' if (ratio <= 0 or ratio > 1) else '否'
    
    # 小金额标记
    small_amount = '是' if (budget <= 100 or winning <= 100) else '否'
    
    # 极端价格异常标记
    extreme = '否'
    if ratio > 10 or ratio < 0.001:
        extreme = '是'
    elif budget <= 100 and winning > 10000:
        extreme = '是'
    elif winning <= 100 and budget > 10000:
        extreme = '是'
    
    # 价格有效样本
    valid = '否'
    if (ratio_anomaly == '否' and small_amount == '否' and extreme == '否'):
        valid = '是'
    
    return valid, extreme, ratio_anomaly, small_amount


