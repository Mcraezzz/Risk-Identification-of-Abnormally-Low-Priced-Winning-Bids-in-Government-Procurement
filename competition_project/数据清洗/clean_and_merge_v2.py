# 处理带前缀的城市，如 "新疆乌鲁木齐市" -> 提取 "乌鲁木齐"
PROVINCE_PREFIXES = {
    '新疆': '新疆', '广西': '广西', '宁夏': '宁夏', '内蒙古': '内蒙古',
    '西藏': '西藏',
}


def infer_province_from_city(city):
    """根据城市名称推断省份。"""
    if not city or not str(city).strip():
        return None
    city_str = str(city).strip()
    
    # 直接匹配
    if city_str in CITY_TO_PROVINCE:
        return CITY_TO_PROVINCE[city_str]
    
    # 检查是否以省份前缀开头，如 "新疆乌鲁木齐市"
    for prefix, prov in PROVINCE_PREFIXES.items():
        if city_str.startswith(prefix):
            # 尝试提取城市名
            remainder = city_str[len(prefix):]
            if remainder in CITY_TO_PROVINCE:
                return CITY_TO_PROVINCE[remainder]
            # 去掉可能的 "市" 再试
            if remainder.endswith('市') and remainder[:-1] in CITY_TO_PROVINCE:
                return CITY_TO_PROVINCE[remainder[:-1]]
            # 如果前缀后没有有效城市名，返回前缀省份
            return prov
    
    # 检查是否以 "地区" 结尾
    if city_str.endswith('地区'):
        base = city_str[:-2]
        if base in CITY_TO_PROVINCE:
            return CITY_TO_PROVINCE[base]
    
    # 去掉末尾的 "市" 再试
    if city_str.endswith('市'):
        base = city_str[:-1]
        if base in CITY_TO_PROVINCE:
            return CITY_TO_PROVINCE[base]
    
    return None


